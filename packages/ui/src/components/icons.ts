import { html, raw } from 'hono/html';

/**
 * Inline SVG icons, sized in em so they track the text beside them.
 *
 * Inline rather than a webfont or a sprite: a forum ships to people who will
 * self-host it, and every extra asset is one more thing to lose. The paths are
 * Lucide's, which is what shadcn itself uses.
 */
function icon(body: string, label?: string) {
  return html`<svg
    xmlns="http://www.w3.org/2000/svg"
    width="1em"
    height="1em"
    viewBox="0 0 24 24"
    fill="none"
    stroke="currentColor"
    stroke-width="2"
    stroke-linecap="round"
    stroke-linejoin="round"
    ${label ? raw(`role="img" aria-label="${label}"`) : raw('aria-hidden="true"')}
  >${raw(body)}</svg>`;
}

